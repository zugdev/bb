import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import type { ThreadDelta } from "@get-bb/plugin-sdk/provider-bridge";
import { afterEach, describe, expect, it } from "vitest";
import {
  listClaudeSessions,
  readClaudeSession,
  splitClaudeTranscript,
} from "./session-import.js";

const SESSION_ID = "0f6f2a8e-1c1b-4c55-9b7e-3f0c5d2a9e11";
const CWD = "/tmp/bb-import-demo";

function assistant(uuid: string, timestamp: string, content: unknown[]) {
  return {
    type: "assistant",
    uuid,
    sessionId: SESSION_ID,
    cwd: CWD,
    timestamp,
    message: {
      id: `msg_${uuid}`,
      type: "message",
      role: "assistant",
      model: "claude-test",
      content,
    },
  };
}

function user(
  uuid: string,
  timestamp: string,
  content: unknown,
  extra: Record<string, unknown> = {},
) {
  return {
    type: "user",
    uuid,
    sessionId: SESSION_ID,
    cwd: CWD,
    timestamp,
    message: { role: "user", content },
    ...extra,
  };
}

const TRANSCRIPT = [
  { type: "file-history-snapshot", messageId: "snap-1", snapshot: {} },
  user("u1", "2026-01-02T03:04:05.000Z", "List the files"),
  assistant("a1", "2026-01-02T03:04:06.000Z", [
    {
      type: "tool_use",
      id: "toolu_list",
      name: "Bash",
      input: { command: "ls", description: "List files" },
    },
  ]),
  user("u2", "2026-01-02T03:04:07.000Z", [
    {
      type: "tool_result",
      tool_use_id: "toolu_list",
      content: "notes.txt",
      is_error: false,
    },
  ]),
  assistant("a2", "2026-01-02T03:04:08.000Z", [
    { type: "text", text: "There is one file, notes.txt." },
  ]),
  assistant("side1", "2026-01-02T03:04:09.000Z", [
    { type: "text", text: "sidechain chatter" },
  ]),
  user("meta1", "2026-01-02T03:04:10.000Z", "Caveat: generated by a command", {
    isMeta: true,
  }),
  user("u3", "2026-01-02T03:05:00.000Z", [{ type: "text", text: "Thanks" }]),
  assistant("a3", "2026-01-02T03:05:01.000Z", [
    { type: "text", text: "You are welcome." },
  ]),
].map((entry) =>
  "uuid" in entry && entry.uuid === "side1"
    ? { ...entry, isSidechain: true }
    : entry,
);

function deltasOf(turn: { steps: { deltas: ThreadDelta[] }[] }): ThreadDelta[] {
  return turn.steps.flatMap((step) => step.deltas);
}

function textOf(deltas: readonly ThreadDelta[]): string {
  return JSON.stringify(deltas);
}

describe("splitClaudeTranscript", () => {
  it("splits at typed prompts and keeps tool results inside their turn", () => {
    const split = splitClaudeTranscript(TRANSCRIPT, {
      fallbackTime: 0,
      maxTurns: 500,
    });

    expect(split.cwd).toBe(CWD);
    expect(split.truncated).toBe(false);
    expect(split.turns.map((turn) => turn.prompt)).toEqual([
      "List the files",
      "Thanks",
    ]);
    const [first, second] = split.turns;
    expect(first?.startedAt).toBe(Date.parse("2026-01-02T03:04:05.000Z"));
    const firstDeltas = deltasOf(first!);
    expect(firstDeltas[0]).toEqual({ kind: "turn.open" });
    expect(firstDeltas.at(-1)).toEqual({
      kind: "turn.boundary",
      status: "completed",
    });
    const toolOpen = firstDeltas.find(
      (delta) =>
        delta.kind === "item.open" && delta.key.providerItemId === "toolu_list",
    );
    const toolClose = firstDeltas.find(
      (delta) =>
        delta.kind === "item.close" &&
        delta.key.providerItemId === "toolu_list",
    );
    expect(toolOpen).toBeDefined();
    expect(toolClose).toBeDefined();
    expect(textOf(firstDeltas)).toContain("There is one file, notes.txt.");
    expect(textOf(firstDeltas)).not.toContain("sidechain chatter");
    expect(textOf(firstDeltas)).not.toContain("Caveat: generated");
    expect(textOf(deltasOf(second!))).toContain("You are welcome.");
    expect(
      deltasOf(second!).filter((delta) => delta.kind === "turn.boundary"),
    ).toHaveLength(1);
  });

  it("unwraps pasted content tags in prompts", () => {
    const split = splitClaudeTranscript(
      [
        user(
          "p1",
          "2026-01-02T03:04:05.000Z",
          '<pasted_content id="40b3">\nfirst line\nsecond line\n</pasted_content>\nsummarize this',
        ),
      ],
      { fallbackTime: 0, maxTurns: 500 },
    );

    expect(split.turns.map((turn) => turn.prompt)).toEqual([
      "first line\nsecond line\n\nsummarize this",
    ]);
  });

  it("keeps the most recent turns when the transcript exceeds the cap", () => {
    const split = splitClaudeTranscript(TRANSCRIPT, {
      fallbackTime: 0,
      maxTurns: 1,
    });

    expect(split.truncated).toBe(true);
    expect(split.turns.map((turn) => turn.prompt)).toEqual(["Thanks"]);
  });
});

describe("Claude session files", () => {
  const tempDirs: string[] = [];

  afterEach(() => {
    for (const dir of tempDirs.splice(0)) {
      rmSync(dir, { recursive: true, force: true });
    }
  });

  function writeConfigDirectory(): string {
    const configDirectory = mkdtempSync(join(tmpdir(), "bb-claude-import-"));
    tempDirs.push(configDirectory);
    const projectDirectory = join(
      configDirectory,
      "projects",
      "-tmp-bb-import-demo",
    );
    mkdirSync(join(projectDirectory, SESSION_ID, "subagents"), {
      recursive: true,
    });
    writeFileSync(
      join(projectDirectory, `${SESSION_ID}.jsonl`),
      `${TRANSCRIPT.map((entry) => JSON.stringify(entry)).join("\n")}\n`,
    );
    writeFileSync(
      join(projectDirectory, "empty-session.jsonl"),
      `${JSON.stringify({ type: "summary", summary: "nothing typed" })}\n`,
    );
    return configDirectory;
  }

  it("lists sessions with their cwd and first prompt", async () => {
    const configDirectory = writeConfigDirectory();

    const result = await listClaudeSessions({ configDirectory });

    expect(result.sessions).toEqual([
      expect.objectContaining({
        sessionId: SESSION_ID,
        cwd: CWD,
        title: "List the files",
      }),
    ]);
    expect(result.sessions[0]?.sizeBytes).toBeGreaterThan(0);
  });

  it("reads a session by id and rejects an unknown one", async () => {
    const configDirectory = writeConfigDirectory();

    const session = await readClaudeSession({
      configDirectory,
      sessionId: SESSION_ID,
    });

    expect(session.cwd).toBe(CWD);
    expect(session.turns).toHaveLength(2);
    await expect(
      readClaudeSession({ configDirectory, sessionId: "missing" }),
    ).rejects.toThrow("Claude session missing was not found");
  });
});
